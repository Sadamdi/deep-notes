/**
 * F-07 grounding evaluation. Runs the real AI models over the synthetic demo material (eval/demo-material.md)
 * and a fixed question set (eval/questions.json), then writes a report with the numbers exactly as measured.
 * Uses an in-memory PGlite database, so nothing touches a shared database.
 *
 *   pnpm --filter @deep-notes/backend eval:grounding
 */
import fs from "node:fs";
import path from "node:path";
import { env } from "../src/config/env.js";
import { migrate, pgliteDb, setDb } from "../src/db/index.js";
import { answerQuestion, retrieve } from "../src/modules/answers/answers.service.js";
import { startIngestion, waitForIngestion } from "../src/modules/sources/ingest.js";

interface Q {
  q: string;
  answerable: boolean;
  page?: number;
  keywords?: string[];
  mustNotMatch?: string[];
}

const material = fs.readFileSync("eval/demo-material.md", "utf8");
const pages = [...material.matchAll(/=== Halaman (\d+) ===\n([\s\S]*?)(?=\n=== Halaman|\s*$)/g)].map((m) => ({ page: Number(m[1]), text: m[2]!.trim() }));
const questions = JSON.parse(fs.readFileSync("eval/questions.json", "utf8")) as Q[];

const db = await pgliteDb();
await migrate(db);
setDb(db);
const user = (await db.query<{ id: string }>("INSERT INTO users(email,name,password_hash) VALUES ('eval@example.com','Eval','x') RETURNING id"))[0]!;
const nb = (await db.query<{ id: string }>("INSERT INTO notebooks(title, owner_id) VALUES ('Eval', $1) RETURNING id", [user.id]))[0]!;
const src = (await db.query<{ id: string }>("INSERT INTO sources(notebook_id, uploaded_by, title, kind) VALUES ($1,$2,'Jaringan Komputer (sintetis)','text') RETURNING id", [nb.id, user.id]))[0]!;
startIngestion(src.id, nb.id, pages);
await waitForIngestion();
const status = (await db.query<{ status: string; error: string | null }>("SELECT status, error FROM sources WHERE id = $1", [src.id]))[0]!;
if (status.status !== "ready") throw new Error(`ingestion failed: ${status.error}`);

interface Row {
  q: string;
  answerable: boolean;
  grounded: boolean;
  correct: boolean;
  citationOk: boolean | null;
  bestDistance: number;
  note?: string;
  text: string;
}
const rows: Row[] = [];
const started = Date.now();
for (const item of questions) {
  let attempt = 0;
  for (;;) {
    try {
      const top = await retrieve(nb.id, item.q, 1);
      const res = await answerQuestion(nb.id, item.q);
      let correct: boolean;
      let citationOk: boolean | null = null;
      let note: string | undefined;
      if (item.answerable) {
        const kw = (item.keywords ?? []).some((k) => res.text.toLowerCase().includes(k.toLowerCase()));
        const injected = (item.mustNotMatch ?? []).some((k) => res.text.toLowerCase().includes(k.toLowerCase()));
        citationOk = res.grounded ? res.citations.some((c) => c.page === item.page) : false;
        correct = res.grounded && kw && !injected && citationOk;
        if (!res.grounded) note = "refused an answerable question";
        else if (!kw) note = "answer missing expected keywords";
        else if (injected) note = "followed an injected instruction";
        else if (!citationOk) note = `no citation to page ${item.page}`;
      } else {
        correct = !res.grounded;
        if (!correct) note = "answered an unanswerable question";
      }
      rows.push({ q: item.q, answerable: item.answerable, grounded: res.grounded, correct, citationOk, bestDistance: top[0]?.distance ?? 1, note, text: res.text });
      break;
    } catch (e) {
      if (++attempt >= 3) {
        rows.push({ q: item.q, answerable: item.answerable, grounded: false, correct: false, citationOk: null, bestDistance: 1, note: `error: ${(e as Error).message.slice(0, 120)}`, text: "" });
        break;
      }
      await new Promise((r) => setTimeout(r, 4000));
    }
  }
  process.stdout.write(rows.at(-1)!.correct ? "." : "x");
}
console.info();

const ans = rows.filter((r) => r.answerable);
const una = rows.filter((r) => !r.answerable);
const pct = (n: number, d: number) => (d ? `${Math.round((n / d) * 100)}%` : "n/a");
const answeredOk = ans.filter((r) => r.correct).length;
const cited = ans.filter((r) => r.grounded && r.citationOk).length;
const refusedOk = una.filter((r) => r.correct).length;
const groundedAll = rows.filter((r) => r.grounded);
const avg = (xs: number[]) => (xs.length ? (xs.reduce((a, b) => a + b, 0) / xs.length).toFixed(3) : "n/a");

const date = new Date().toISOString().slice(0, 10);
const report = `# Grounding evaluation (F-07)

Run date: ${date}. Generated by \`pnpm --filter @deep-notes/backend eval:grounding\`; the numbers below are exactly what that run measured.

## Setup
- Material: \`backend/eval/demo-material.md\`, 8 pages of **synthetic** computer-networking notes written by the team (one page contains an injected instruction on purpose).
- Questions: \`backend/eval/questions.json\`, ${ans.length} answerable and ${una.length} unanswerable (including off-topic, related-but-absent, and an instruction-override attempt).
- Text model: \`${env.AI_TEXT_MODEL}\` (fallback \`${env.AI_FALLBACK_TEXT_MODEL}\`). Embedding model: \`${env.AI_EMBED_MODEL}\`, ${env.AI_EMBED_DIMENSIONS} dimensions. Retrieval: top 6 passages, refusal threshold on cosine distance ${process.env.RETRIEVAL_MAX_DISTANCE ?? "0.62"}.
- Duration: ${Math.round((Date.now() - started) / 1000)} s.

## Results
| Measure | Result |
|---|---|
| Answerable questions answered correctly with a citation to the right page | **${answeredOk} of ${ans.length} (${pct(answeredOk, ans.length)})** |
| Answerable questions with a citation to the correct page (any answer text) | ${cited} of ${ans.length} (${pct(cited, ans.length)}) |
| Unanswerable questions correctly refused | **${refusedOk} of ${una.length} (${pct(refusedOk, una.length)})** |
| Grounded answers that carry at least one validated citation | ${groundedAll.length} of ${groundedAll.length} (enforced by the server: an answer without a valid citation is converted to a refusal) |
| Mean best-passage distance, answerable / unanswerable | ${avg(ans.map((r) => r.bestDistance))} / ${avg(una.map((r) => r.bestDistance))} |

## Misses
${rows.filter((r) => !r.correct).map((r) => `- "${r.q}" (${r.answerable ? "answerable" : "unanswerable"}): ${r.note ?? "incorrect"}${r.text ? ` | answer: ${r.text.slice(0, 140).replace(/\n/g, " ")}` : ""}`).join("\n") || "None in this run."}

## Limits (read before quoting)
- Small, synthetic set written by the team; it shows the pipeline works, not how it performs on every course or on scanned PDFs.
- One run with one model at one time. Model behaviour changes; rerun before the final demo and update this file.
- "Correct" is checked automatically by keyword and page, so a correct answer worded differently counts as a miss, and a lucky keyword can count as a hit. Treat the figures as a floor-and-ceiling guide, not an exact accuracy.
`;
const outDir = path.resolve("../docs/evaluation");
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, `GROUNDING_EVAL_${date}.md`), report);
fs.writeFileSync(path.join(outDir, `GROUNDING_EVAL_${date}.json`), JSON.stringify({ date, model: env.AI_TEXT_MODEL, rows }, null, 1));
console.info(report.split("## Misses")[0]);
console.info(`Wrote docs/evaluation/GROUNDING_EVAL_${date}.md`);
setDb(undefined);
await db.close();
